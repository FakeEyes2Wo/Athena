export type IconName = keyof typeof ICONS;

interface IconProps {
  name: IconName;
  size?: number;
  className?: string;
  strokeWidth?: number;
}

/** Crisp, consistent SVG icon. Decorative by default (hidden from assistive tech). */
export function Icon({ name, size = 16, className, strokeWidth = 1.85 }: IconProps) {
  const Component: LucideIcon = ICONS[name];
  return <Component size={size} className={className} strokeWidth={strokeWidth} aria-hidden />;
}
