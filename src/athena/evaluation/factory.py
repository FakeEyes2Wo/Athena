"""EvalSpec 默认指标：按 task_type 构造主/次指标协议。"""

import json

from athena.evaluation.types import EvalSpec, MetricDef

_DEFAULT_METRICS = {
    "classification": MetricDef(
        name="f1_macro",
        direction="maximize",
        description="F1 score with macro averaging across classes",
    ),
    "regression": MetricDef(
        name="rmse", direction="minimize", description="Root Mean Squared Error"
    ),
    "binary_classification": MetricDef(
        name="roc_auc",
        direction="maximize",
        description="Area Under the ROC Curve",
    ),
}


def create_eval_spec(task_type: str) -> EvalSpec:
    """Create the frozen default metric protocol for one task type."""
    primary = _DEFAULT_METRICS.get(
        task_type,
        MetricDef(name="accuracy", direction="maximize", description="Accuracy"),
    )
    spec = EvalSpec(
        primary=MetricDef(
            name=primary.name,
            direction=primary.direction,
            description=primary.description,
        ),
        secondary=_default_secondary(task_type),
    )
    return spec.model_copy(update={"eval_script": default_eval_script(spec)})


def default_eval_script(spec: EvalSpec) -> str:
    """Render a self-contained frozen evaluator for catalog metrics."""
    primary = json.dumps(spec.primary.name)
    secondary = json.dumps([metric.name for metric in spec.secondary])
    return f'''"""Frozen evaluator generated by Athena. Do not edit."""
import json
import math
import os

import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    f1_score,
    mean_absolute_error,
    mean_squared_error,
    precision_score,
    r2_score,
    recall_score,
    roc_auc_score,
)


def metric(name, y_true, y_pred):
    if name == "accuracy":
        return float(accuracy_score(y_true, y_pred))
    if name in {{"f1", "f1_binary"}}:
        return float(f1_score(y_true, y_pred, zero_division=0))
    if name == "f1_macro":
        return float(f1_score(y_true, y_pred, average="macro", zero_division=0))
    if name == "precision":
        return float(precision_score(y_true, y_pred, zero_division=0))
    if name == "precision_macro":
        return float(precision_score(y_true, y_pred, average="macro", zero_division=0))
    if name == "recall":
        return float(recall_score(y_true, y_pred, zero_division=0))
    if name == "recall_macro":
        return float(recall_score(y_true, y_pred, average="macro", zero_division=0))
    if name == "roc_auc":
        return float(roc_auc_score(y_true, y_pred))
    if name == "mae":
        return float(mean_absolute_error(y_true, y_pred))
    if name == "mse":
        return float(mean_squared_error(y_true, y_pred))
    if name == "rmse":
        return float(math.sqrt(mean_squared_error(y_true, y_pred)))
    if name == "r2":
        return float(r2_score(y_true, y_pred))
    raise ValueError(f"unsupported frozen metric: {{name}}")


predictions = pd.read_csv("predictions.csv").iloc[:, 0]
labels = pd.read_csv("labels.csv").iloc[:, 0]
if len(predictions) != len(labels) or not len(labels):
    raise ValueError("predictions and labels must have the same non-zero length")
primary_name = {primary}
secondary_names = {secondary}
payload = {{
    "experiment_id": os.environ["ATHENA_EXPERIMENT_ID"],
    "primary": metric(primary_name, labels, predictions),
    "secondary": {{name: metric(name, labels, predictions) for name in secondary_names}},
}}
with open("eval_result.json", "w", encoding="utf-8") as stream:
    json.dump(payload, stream, indent=2, sort_keys=True)
'''


def _default_secondary(task_type: str) -> list[MetricDef]:
    if task_type == "classification":
        return [
            MetricDef(name="accuracy", direction="maximize", description="Accuracy"),
            MetricDef(
                name="precision_macro",
                direction="maximize",
                description="Precision macro",
            ),
            MetricDef(
                name="recall_macro",
                direction="maximize",
                description="Recall macro",
            ),
        ]
    if task_type == "regression":
        return [
            MetricDef(
                name="mae", direction="minimize", description="Mean Absolute Error"
            ),
            MetricDef(name="r2", direction="maximize", description="R-squared"),
        ]
    if task_type == "binary_classification":
        return [
            MetricDef(name="f1", direction="maximize", description="F1 score"),
            MetricDef(name="precision", direction="maximize", description="Precision"),
            MetricDef(name="recall", direction="maximize", description="Recall"),
        ]
    return []


if __name__ == "__main__":
    spec = create_eval_spec("classification")
    print(f"create_eval_spec('classification') -> {spec.primary.name}")
